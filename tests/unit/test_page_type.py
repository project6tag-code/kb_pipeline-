"""Gate 16 page-type / synthetic-content checks (ptype1) and CC index-range planning, offline."""

import unittest

from app.processing.quality import page_type
from app.processing.quality.scorer import features
from app.sources.commoncrawl.config import FilterConfig, PlanningConfig
from app.sources.commoncrawl.discovery import block_selector, plan_partitions, surt_host_prefixes

ARTICLE = ("Photosynthesis is the process by which green plants and some other organisms use sunlight to "
           "synthesize foods from carbon dioxide and water. It generally involves the green pigment chlorophyll "
           "and generates oxygen as a byproduct. The process takes place in the chloroplasts. ") * 4


def check(text=ARTICLE, url="https://en.wikipedia.org/wiki/Photosynthesis", title="Photosynthesis - Wikipedia"):
    return page_type.check(url, title, text, features(text))


class PageTypeTests(unittest.TestCase):
    def test_article_passes(self) -> None:
        self.assertEqual(check().reasons, ())
        for title in ("National Register of Historic Places", "New Deal", "National Archives and Records Administration"):
            with self.subTest(title=title):
                self.assertTrue(check(title=title).passed)

    def test_non_content_urls_and_titles(self) -> None:
        self.assertIn("non_content_url:ip_host", check(url="http://75.34.128.137/shoprd/a.htm").reasons)
        for title in ("Shopping Cart - Store", "Terms of Use | Example", "Privacy Policy", "Search results for oxygen",
                      "Page 3 of 12", "Monthly Archives: May 2019", "Log in to your account", "404 Page Not Found"):
            with self.subTest(title=title):
                self.assertIn("non_content_title", check(title=title).reasons)

    def test_commerce_listing_and_forum_pages(self) -> None:
        shop = ARTICLE + " Add to cart. In stock. SKU 1234. Free shipping on orders. "
        self.assertIn("commerce_page", check(shop).reasons)
        prices = ARTICLE + " ".join(f"Item {i} $1{i}.99" for i in range(10))
        self.assertIn("commerce_page", check(prices).reasons)
        listing = ARTICLE + " Read more. " * 4
        self.assertIn("listing_page", check(listing).reasons)
        forum = "Posted by user1. Reply. Quote. Joined: 2010. Posts: 5. Reply. Quote. " * 3
        self.assertIn("forum_or_comments", check(forum).reasons)

    def test_synthetic_and_placeholder_content(self) -> None:
        for marker in ("As an AI language model, I cannot browse.", "This article was generated by AI.",
                       "Lorem ipsum dolor sit amet.", "This is a sample page for the theme.",
                       "Contact [insert company name] today.", "Hello {{ customer_name }}!",
                       "Hello world! Welcome to WordPress."):
            with self.subTest(marker=marker):
                self.assertIn("synthetic_or_placeholder", check(ARTICLE + " " + marker).reasons)
        self.assertTrue(check(ARTICLE + " ChatGPT is a chatbot developed by OpenAI.").passed)

    def test_declared_schema_types(self) -> None:
        # A real eBay item page (CC-MAIN-2024-33) passed every other gate; it declares @type Product / Offer.
        html = ('<script type="application/ld+json">{"@context":"https://schema.org","@type":"Product",'
                '"name":"Fire Starter","offers":{"@type":"Offer","price":"7.99"}}</script>'
                '<script type="application/ld+json">{"@type":["WebPage","https://schema.org/SearchResultsPage"]}'
                '</script>')
        declared = page_type.schema_types(html)
        self.assertEqual(declared, frozenset({"Product", "WebPage", "SearchResultsPage"}))
        reasons = page_type.check("https://www.ebay.com/itm/291826211786", "Fire Starter | eBay", ARTICLE,
                                  features(ARTICLE), declared).reasons
        self.assertEqual([r for r in reasons if r.startswith("schema_type:")],
                         ["schema_type:Product", "schema_type:SearchResultsPage"])
        article = page_type.schema_types('<script type="application/ld+json">{"@type":"Article"}</script>')
        self.assertTrue(page_type.check(None, "Oxygen", ARTICLE, features(ARTICLE), article).passed)
        self.assertEqual(page_type.schema_types("<p>no json-ld</p>"), frozenset())

    def test_marketplace_item_text(self) -> None:
        item = ARTICLE + " Have one to sell? Sell now. US $7.99. Condition: New. Quantity: 3. 3,786 sold. Shipping: Free."
        self.assertIn("commerce_page", check(item).reasons)

    def test_technical_vocabulary_is_not_commerce(self) -> None:
        # A real Stack Overflow git page was flagged by "checkout" / "Returns:" before these were dropped.
        docs = ARTICLE + " Run git checkout main. Returns: the new branch. Shipping: see the release notes."
        self.assertNotIn("commerce_page", check(docs).reasons)


class LowInformationWindowTests(unittest.TestCase):
    def test_long_varied_article_is_not_low_information(self) -> None:
        # noise1 measured the unique-word ratio over the whole text, so a real 17k-word Stanford Encyclopedia
        # of Philosophy entry was rejected; noise2 measures it over a fixed 1,000-word window.
        from app.processing.quality import spam

        vocabulary = [f"term{i}" for i in range(600)]
        long_text = " ".join(f"The {w} relates to {vocabulary[(i * 7) % 600]} by definition."
                             for i, w in enumerate(vocabulary * 20))
        f = features(long_text)
        self.assertLess(f.unique_ratio, 0.15)  # the whole-text ratio that noise1 used
        self.assertNotIn("low_information", spam.check(long_text, f, kind="prose", min_words=80).reasons)
        repetitive = "the cat sat on the mat " * 400
        self.assertIn("low_information", spam.check(repetitive, features(repetitive), kind="prose", min_words=80).reasons)


class IndexRangePlanningTests(unittest.TestCase):
    KEYS = ["1,2,3,4)/a", "9,9,9)/x", "com,aaa)/", "org,wikipedia,de)/", "org,wikipedia,en)/wiki/a",
            "org,wikipedia,en)/wiki/z", "org,wikipedia,fr)/", "zz,zz)/"]

    def lines(self):
        return [f"{key} 20240101000000\tcdx-00000.gz\t{i * 10}\t10\t{i}".encode() for i, key in enumerate(self.KEYS)]

    def planned(self, filter_config, **planning):
        config = PlanningConfig(blocks_per_partition=planning.pop("blocks", 1), **planning)
        return [(p.first_block, p.last_block) for p in plan_partitions(
            self.lines(), "CC-MAIN-2024-10", config, max_block_bytes=100, selector=block_selector(filter_config))]

    def test_surt_prefixes(self) -> None:
        self.assertEqual(surt_host_prefixes("www.britannica.com"), ("com,britannica)", "com,britannica,"))
        self.assertEqual(surt_host_prefixes("en.wikipedia.org"), ("org,wikipedia,en)", "org,wikipedia,en,"))

    def test_reference_profile_reads_only_the_listed_key_ranges(self) -> None:
        reference = FilterConfig(profile="reference", reference_domains=("en.wikipedia.org",))
        # block 3 starts before en.wikipedia but runs into it; block 6 (fr) cannot hold it
        self.assertEqual(self.planned(reference), [(3, 3), (4, 4), (5, 5)])
        self.assertEqual(self.planned(reference, max_partitions_per_crawl=1), [(3, 3)])

    def test_open_profile_skips_the_raw_ip_region(self) -> None:
        self.assertEqual(self.planned(FilterConfig())[0], (1, 1))
        self.assertNotIn((0, 0), self.planned(FilterConfig()))
        self.assertEqual(self.planned(FilterConfig(), blocks=2), [(0, 1), (2, 3), (4, 5), (6, 7)])

    def test_stride_counts_selected_partitions_only(self) -> None:
        self.assertEqual(self.planned(FilterConfig(), partition_stride=3), [(1, 1), (4, 4), (7, 7)])


if __name__ == "__main__":
    unittest.main()
